import {
	Baby,
	BookOpen,
	Clapperboard,
	Drama,
	Film,
	Ghost,
	Heart,
	Landmark,
	Laugh,
	type LucideIcon,
	Map as MapIcon,
	MessagesSquare,
	Music,
	Popcorn,
	Rocket,
	Search,
	Shield,
	Skull,
	Sparkles,
	Swords,
	Tv,
	Users,
	Wand,
	Zap,
} from "lucide-react";

/** Icons for the discover genres, keyed by slug. */
const GENRE_ICONS: Record<string, LucideIcon> = {
	action: Zap,
	adventure: MapIcon,
	animation: Sparkles,
	comedy: Laugh,
	crime: Shield,
	documentary: BookOpen,
	drama: Drama,
	family: Users,
	fantasy: Wand,
	history: Landmark,
	horror: Ghost,
	kids: Baby,
	music: Music,
	mystery: Search,
	reality: Popcorn,
	romance: Heart,
	"science-fiction": Rocket,
	soap: MessagesSquare,
	thriller: Skull,
	"tv-movie": Tv,
	war: Swords,
	western: Clapperboard,
};

export const getGenreIcon = (genreSlug: string): LucideIcon =>
	GENRE_ICONS[genreSlug] ?? Film;
